/// `[apps]`: settings for every app.
#[derive(Debug, Serialize, Deserialize, Clone, Default, PartialEq)]
#[serde(default, deny_unknown_fields)]
pub struct AppsConfig {
    /// Directories an app's env file (dashboard Settings → Env file) may be
    /// in, after symbolic links are resolved. Empty (the default) turns env
    /// files off.
    pub env_file_dirs: Vec<PathBuf>,
}

impl AppsConfig {
    pub fn validate(&self) -> Result<(), anyhow::Error> {
        for dir in &self.env_file_dirs {
            let text = dir.to_string_lossy();
            if !dir.is_absolute()
                || dir
                    .components()
                    .any(|c| matches!(c, std::path::Component::ParentDir))
            {
                anyhow::bail!(
                    "apps.env_file_dirs: '{}' must be an absolute path without '..'",
                    text
                );
            }
            if dir.parent().is_none() {
                anyhow::bail!(
                    "apps.env_file_dirs: '{}' would allow every file on the server; name the directories that hold env files",
                    text
                );
            }
        }
        Ok(())
    }
}

/// `[update]`: checks for new Aegis releases on GitHub.
#[derive(Debug, Serialize, Deserialize, Clone, PartialEq)]
#[serde(default, deny_unknown_fields)]
pub struct UpdateConfig {
    /// Ask the GitHub releases API for the latest stable release every
    /// `interval_hours`. When false the daemon makes no update-related
    /// network requests at all, and upgrades from the dashboard are off.
    pub check: bool,
    /// Hours between checks.
    pub interval_hours: u64,
    /// The GitHub repository releases come from, as `owner/name` (for forks).
    pub repo: String,
}

impl Default for UpdateConfig {
    fn default() -> Self {
        Self {
            check: true,
            interval_hours: 12,
            repo: "shivam411/Aegis".into(),
        }
    }
}

impl UpdateConfig {
    pub fn validate(&self) -> Result<(), anyhow::Error> {
        if !(1..=24 * 31).contains(&self.interval_hours) {
            anyhow::bail!("update.interval_hours must be 1-744");
        }
        let part_ok = |s: &str| {
            !s.is_empty()
                && s != "."
                && s != ".."
                && s.chars()
                    .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.'))
        };
        match self.repo.split_once('/') {
            Some((owner, name)) if part_ok(owner) && part_ok(name) => Ok(()),
            _ => anyhow::bail!("update.repo must be a GitHub repository like \"owner/name\""),
        }
    }
}

/// `[backup]`: scheduled backups of the database, the secrets key,
/// certificates and (optionally) release directories.
#[derive(Debug, Serialize, Deserialize, Clone, PartialEq)]
#[serde(default, deny_unknown_fields)]
pub struct BackupConfig {
    /// Run scheduled backups. Manual backups (dashboard, API,
    /// `aegis-daemon admin backup`) work either way.
    pub enabled: bool,
    /// Hours between scheduled backups (ignored when `daily_at` is set).
    pub interval_hours: u64,
    /// Back up once a day at this time, "HH:MM" in UTC.
    pub daily_at: Option<String>,
    /// How many backups to keep in `<data_dir>/backups`; older ones are deleted.
    pub keep: usize,
    /// Include release directories (can be large). The database, the
    /// secrets key and certificates are always included.
    pub include_releases: bool,
}

impl Default for BackupConfig {
    fn default() -> Self {
        Self {
            enabled: false,
            interval_hours: 24,
            daily_at: None,
            keep: 7,
            include_releases: true,
        }
    }
}

impl BackupConfig {
    pub fn validate(&self) -> Result<(), anyhow::Error> {
        if !(1..=24 * 366).contains(&self.interval_hours) {
            anyhow::bail!("backup.interval_hours must be 1-8784");
        }
        if !(1..=1000).contains(&self.keep) {
            anyhow::bail!("backup.keep must be 1-1000");
        }
        if self.daily_at.is_some() && self.daily_time().is_none() {
            anyhow::bail!("backup.daily_at must be a UTC time like \"03:30\"");
        }
        Ok(())
    }

    /// `daily_at` as (hour, minute), if set and valid.
    pub fn daily_time(&self) -> Option<(u32, u32)> {
        let (h, m) = self.daily_at.as_deref()?.trim().split_once(':')?;
        let (h, m): (u32, u32) = (h.parse().ok()?, m.parse().ok()?);
        (h < 24 && m < 60).then_some((h, m))
    }
}

/// `[resources]`: per-app limits and metrics.
#[derive(Debug, Serialize, Deserialize, Clone, PartialEq)]
#[serde(default, deny_unknown_fields)]
pub struct ResourcesConfig {
    /// "auto" (use cgroups when possible) or "off".
    pub cgroups: String,
    /// cgroup v2 only: create app cgroups under this directory instead of
    /// detecting one. It must have the cpu and memory controllers enabled
    /// in its cgroup.subtree_control.
    pub cgroup_root: Option<PathBuf>,
    /// How often apps and the host are measured.
    pub sample_interval_secs: u64,
    /// How long per-minute metric rollups are kept.
    pub retention_days: u64,
}

impl Default for ResourcesConfig {
    fn default() -> Self {
        Self {
            cgroups: "auto".into(),
            cgroup_root: None,
            sample_interval_secs: 2,
            retention_days: 7,
        }
    }
}

impl ResourcesConfig {
    pub fn validate(&self) -> Result<(), anyhow::Error> {
        if !matches!(self.cgroups.as_str(), "auto" | "off") {
            anyhow::bail!("resources.cgroups must be \"auto\" or \"off\"");
        }
        if !(1..=60).contains(&self.sample_interval_secs) {
            anyhow::bail!("resources.sample_interval_secs must be 1-60");
        }
        if !(1..=365).contains(&self.retention_days) {
            anyhow::bail!("resources.retention_days must be 1-365");
        }
        if let Some(root) = &self.cgroup_root {
            if !root.is_absolute() {
                anyhow::bail!("resources.cgroup_root must be an absolute path");
            }
        }
        Ok(())
    }
}

