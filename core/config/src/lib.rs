impl ProxyConfig {
    /// The parsed `trusted_proxies` list.
    ///
    /// Every entry must be an IP address or a CIDR range; host names are
    /// refused (they would be resolved once and silently go stale), and so
    /// are ranges that cover the whole address space (`0.0.0.0/0`, `::/0`),
    /// which would let any client spoof the forwarded headers.
    pub fn trusted_proxy_ranges(&self) -> Result<Vec<aegis_types::net::IpCidr>, anyhow::Error> {
        self.trusted_proxies
            .iter()
            .map(|entry| {
                let cidr: aegis_types::net::IpCidr = entry
                    .parse()
                    .map_err(|e| anyhow::anyhow!("proxy.trusted_proxies: {}", e))?;
                if cidr.prefix() == 0 {
                    anyhow::bail!(
                        "proxy.trusted_proxies: \"{}\" would trust every client; list only \
                         the addresses of your front proxy (usually \"127.0.0.1\" and \"::1\")",
                        entry
                    );
                }
                Ok(cidr)
            })
            .collect()
    }

    /// The entries of `trusted_proxies` that are not loopback addresses.
    /// They are allowed, but anyone who can connect from those addresses can
    /// set the forwarded headers, so the daemon warns about them.
    pub fn non_loopback_trusted_proxies(&self) -> Vec<String> {
        self.trusted_proxy_ranges()
            .unwrap_or_default()
            .into_iter()
            .filter(|c| !c.is_loopback())
            .map(|c| c.to_string())
            .collect()
    }

    /// Checks the `[proxy]` section; `web` and `daemon` are needed to rule
    /// out port clashes and to check the dashboard route.
    pub fn validate(&self, web: &WebConfig, daemon: &DaemonConfig) -> Result<(), anyhow::Error> {
        self.trusted_proxy_ranges()?;
        if !PROXY_RESPONSE_TIMEOUT_RANGE.contains(&self.response_timeout_secs) {
            anyhow::bail!(
                "proxy.response_timeout_secs must be {}-{} (got {})",
                PROXY_RESPONSE_TIMEOUT_RANGE.start(),
                PROXY_RESPONSE_TIMEOUT_RANGE.end(),
                self.response_timeout_secs
            );
        }
        if !PROXY_CONNECT_TIMEOUT_RANGE.contains(&self.connect_timeout_secs) {
            anyhow::bail!(
                "proxy.connect_timeout_secs must be {}-{} (got {})",
                PROXY_CONNECT_TIMEOUT_RANGE.start(),
                PROXY_CONNECT_TIMEOUT_RANGE.end(),
                self.connect_timeout_secs
            );
        }
        if !self.enabled {
            return Ok(());
        }
        if self.host.parse::<std::net::IpAddr>().is_err() {
            anyhow::bail!(
                "proxy.host must be an IP address such as \"0.0.0.0\" (got \"{}\")",
                self.host
            );
        }
        if self.http_port == 0 || self.https_port == 0 || self.http_port == self.https_port {
            anyhow::bail!("proxy.http_port and proxy.https_port must be different, non-zero ports");
        }
        for port in [self.http_port, self.https_port] {
            if (web.enabled && port == web.port) || port == daemon.port {
                anyhow::bail!(
                    "proxy port {} is already used by the HTTP API or the gRPC API",
                    port
                );
            }
        }
        if self.acme.enabled {
            if let Some(email) = &self.acme.email {
                let ok = email.len() <= 254
                    && email
                        .split_once('@')
                        .is_some_and(|(user, host)| !user.is_empty() && host.contains('.'))
                    && !email
                        .chars()
                        .any(|c| c.is_whitespace() || c.is_control() || c == ',');
                if !ok {
                    anyhow::bail!("proxy.acme.email \"{}\" is not a valid address", email);
                }
            }
            if !self.acme.resolved_directory_url().starts_with("https://") {
                anyhow::bail!(
                    "proxy.acme.directory_url must be \"production\", \"staging\" or an https:// URL"
                );
            }
        }
        let dash = &self.dashboard;
        if let Some(domain) = &dash.domain {
            aegis_types::domain::normalize_domain(domain)
                .map_err(|e| anyhow::anyhow!("proxy.dashboard.domain: {}", e))?;
            if !web.enabled {
                anyhow::bail!("proxy.dashboard.domain needs the HTTP API ([web] enabled = true)");
            }
            if web.tls.enabled() {
                anyhow::bail!(
                    "proxy.dashboard.domain: remove [web.tls]; the proxy terminates HTTPS and \
                     forwards to the API on loopback"
                );
            }
            match dash.tls.as_str() {
                "acme" if !self.acme.enabled => anyhow::bail!(
                    "proxy.dashboard.tls = \"acme\" needs [proxy.acme] enabled = true"
                ),
                "acme" => {}
                "files" => {
                    if dash.cert_path.is_none() || dash.key_path.is_none() {
                        anyhow::bail!(
                            "proxy.dashboard.tls = \"files\" needs cert_path and key_path"
                        );
                    }
                }
                _ => anyhow::bail!(
                    "proxy.dashboard.tls must be \"acme\" or \"files\"; the dashboard is never served over plain HTTP"
                ),
            }
        }
        Ok(())
    }
}

/// Resource limits for one app. `None` means unlimited.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct ResourceLimits {
    /// CPU time as a number of cores (0.5 = half of one core).
    pub cpu_cores: Option<f64>,
    /// Hard memory limit in bytes; the soft limit is 90% of it.
    pub memory_bytes: Option<u64>,
    /// Maximum number of processes and threads.
    pub pids_max: Option<u64>,
}

impl ResourceLimits {
    pub fn is_unlimited(&self) -> bool {
        self.cpu_cores.is_none() && self.memory_bytes.is_none() && self.pids_max.is_none()
    }
}

fn is_loopback_host(host: &str) -> bool {
    host == "localhost"
        || host
            .parse::<std::net::IpAddr>()
            .map(|ip| ip.is_loopback())
            .unwrap_or(false)
}

/// TLS certificate files for the HTTP API (PEM). Renewed files are picked up
/// without a restart.
#[derive(Debug, Serialize, Deserialize, Clone, PartialEq, Default)]
#[serde(default)]
pub struct TlsConfig {
    pub cert_path: Option<PathBuf>,
    pub key_path: Option<PathBuf>,
}

impl TlsConfig {
    pub fn enabled(&self) -> bool {
        self.cert_path.is_some() || self.key_path.is_some()
    }
}

/// The HTTP API (and, later, the dashboard) served by the daemon.
#[derive(Debug, Serialize, Deserialize, Clone, PartialEq)]
#[serde(default)]
pub struct WebConfig {
    pub enabled: bool,
    pub host: String,
    pub port: u16,
    /// Public hostnames the API may be reached under (e.g. "aegis.example.com").
    /// Loopback names are always allowed.
    pub allowed_hosts: Vec<String>,
    /// A reverse proxy on this machine terminates HTTPS and forwards to
    /// Aegis on loopback. Enables Secure cookies and HSTS, and uses the
    /// proxy's X-Forwarded-For for login throttling.
    pub behind_proxy: bool,
    pub session_idle_minutes: u64,
    pub session_max_hours: u64,
    pub tls: TlsConfig,
}

impl Default for WebConfig {
    fn default() -> Self {
        Self {
            enabled: false,
            host: "127.0.0.1".to_string(),
            port: 8420,
            allowed_hosts: Vec::new(),
            behind_proxy: false,
            session_idle_minutes: 120,
            session_max_hours: 24,
            tls: TlsConfig::default(),
        }
    }
}

impl WebConfig {
    /// Whether clients reach the API over HTTPS (directly or via the proxy).
    pub fn https(&self) -> bool {
        self.tls.enabled() || self.behind_proxy
    }

    /// Refuses configurations that would expose the API unsafely:
    /// - a non-loopback address without TLS (passwords and session cookies
    ///   would cross the network in clear text);
    /// - public access without `allowed_hosts` (needed for Host checks);
    /// - half-configured TLS.
    pub fn validate(&self) -> Result<(), anyhow::Error> {
        if self.tls.cert_path.is_some() != self.tls.key_path.is_some() {
            anyhow::bail!("web.tls needs both cert_path and key_path");
        }
        if !is_loopback_host(&self.host) && !self.tls.enabled() {
            anyhow::bail!(
                "web.host = \"{}\" is not a loopback address, and web.tls is not configured. \
                 Exposing the API without TLS would send passwords and session cookies in clear text. \
                 Either set [web.tls] cert_path/key_path, or keep web.host = \"127.0.0.1\" and put a \
                 reverse proxy such as Caddy in front with web.behind_proxy = true.",
                self.host
            );
        }
        if (self.behind_proxy || !is_loopback_host(&self.host)) && self.allowed_hosts.is_empty() {
            anyhow::bail!(
                "web.allowed_hosts must list the public hostname(s) of the API (e.g. [\"aegis.example.com\"]) \
                 when it is reachable from outside this machine"
            );
        }
        if self.session_idle_minutes == 0 || self.session_max_hours == 0 {
            anyhow::bail!("web.session_idle_minutes and web.session_max_hours must be positive");
        }
        Ok(())
    }
}

impl DaemonConfig {
    /// The gRPC API has no authentication and is used by the local CLI, so
    /// it must stay on loopback. Remote access goes through the HTTP API.
    pub fn validate(&self) -> Result<(), anyhow::Error> {
        if !is_loopback_host(&self.host) {
            anyhow::bail!(
                "daemon.host = \"{}\" is not a loopback address. The gRPC API is unauthenticated and \
                 only serves the local CLI; use the HTTP API (with a login or API token) for remote access, \
                 or an SSH tunnel.",
                self.host
            );
        }
        Ok(())
    }
}

impl Default for DaemonConfig {
    fn default() -> Self {
        Self {
            host: "127.0.0.1".to_string(),
            port: 50051,
            database_path: PathBuf::from("aegis.db"),
            log_level: "info".to_string(),
            max_retained_versions: 2,
            data_dir: None,
        }
    }
}

impl Config {
    /// Loads the configuration from the specified path.
    pub fn load_from_file<P: AsRef<Path>>(path: P) -> Result<Self, anyhow::Error> {
        let content = std::fs::read_to_string(path)?;
        let config: Config = toml::from_str(&content)?;
        Ok(config)
    }

    /// Loads the file if it exists (defaults otherwise). Unlike
    /// [`Config::load_or_default`], a file that exists but doesn't parse is
    /// an error, so a typo can't silently disable settings.
    pub fn load<P: AsRef<Path>>(path: P) -> Result<Self, anyhow::Error> {
        let path = path.as_ref();
        if !path.exists() {
            return Ok(Self::default());
        }
        Self::load_from_file(path)
            .map_err(|e| anyhow::anyhow!("Invalid configuration in {}: {}", path.display(), e))
    }

    /// Loads the configuration from the specified path or returns the default configuration if loading fails.
    pub fn load_or_default<P: AsRef<Path>>(path: P) -> Self {
        Self::load_from_file(path).unwrap_or_default()
    }
}

